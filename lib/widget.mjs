import { access, appendFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";

/**
 * Feedback widget installer. It writes one self-contained file and the public
 * env values, then tells the agent exactly where to mount it. It never edits
 * the host's layout on its own: the agent does that with the instructions,
 * so the change stays reviewable in the agent's diff.
 *
 * The project key is public by design (it can only create feedback for that
 * project, from the allowed origins), so writing it to an env file is safe.
 */

const exists = (path) =>
  access(path).then(
    () => true,
    () => false,
  );

async function readPackageJson(root) {
  try {
    return JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  } catch {
    return null;
  }
}

const FRAMEWORKS = {
  next: {
    label: "Next.js",
    envPrefix: "NEXT_PUBLIC_",
    envFile: ".env.local",
    react: true,
    envAccess: (name) => `process.env.${name}`,
    clientDirective: true,
  },
  "tanstack-start": {
    label: "TanStack Start",
    envPrefix: "VITE_",
    envFile: ".env.local",
    react: true,
    envAccess: (name) => `import.meta.env.${name}`,
  },
  "react-router": {
    label: "React Router / Remix",
    envPrefix: "VITE_",
    envFile: ".env",
    react: true,
    envAccess: (name) => `import.meta.env.${name}`,
  },
  "vite-react": {
    label: "Vite + React",
    envPrefix: "VITE_",
    envFile: ".env.local",
    react: true,
    envAccess: (name) => `import.meta.env.${name}`,
  },
  astro: { label: "Astro", envPrefix: "PUBLIC_", envFile: ".env", react: false },
  sveltekit: {
    label: "SvelteKit",
    envPrefix: "PUBLIC_",
    envFile: ".env",
    react: false,
  },
  nuxt: { label: "Nuxt", envPrefix: "NUXT_PUBLIC_", envFile: ".env", react: false },
  vue: { label: "Vue", envPrefix: "VITE_", envFile: ".env.local", react: false },
  html: { label: "Plain HTML", envPrefix: "", envFile: null, react: false },
};

export async function detectFramework(root) {
  const pkg = await readPackageJson(root);
  if (!pkg) return { id: "html", ...FRAMEWORKS.html, srcDir: root };
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const has = (name) => Object.hasOwn(deps, name);

  let id = "html";
  if (has("next")) id = "next";
  else if (has("@tanstack/react-start")) id = "tanstack-start";
  else if (has("@remix-run/react") || has("@react-router/dev"))
    id = "react-router";
  else if (has("astro")) id = "astro";
  else if (has("@sveltejs/kit")) id = "sveltekit";
  else if (has("nuxt")) id = "nuxt";
  else if (has("react") && has("vite")) id = "vite-react";
  else if (has("vue")) id = "vue";
  else if (has("react")) id = "vite-react";

  const srcDir = (await exists(join(root, "src"))) ? join(root, "src") : root;
  return {
    id,
    ...FRAMEWORKS[id],
    srcDir,
    typescript: has("typescript") || (await exists(join(root, "tsconfig.json"))),
    hasFeedbackPackage: has("@shyvo/feedback"),
  };
}

const ENV_KEYS = { key: "SHYVO_PROJECT_KEY", endpoint: "SHYVO_ENDPOINT" };

function reactComponent(framework, mode, setup) {
  const key = `${framework.envPrefix}${ENV_KEYS.key}`;
  const endpoint = `${framework.envPrefix}${ENV_KEYS.endpoint}`;
  const directive = framework.clientDirective ? '"use client";\n\n' : "";
  const header = `// Shyvo feedback widget. Generated by \`shyvo widget install\`.
// Mount <ShyvoFeedbackWidget /> once, in the root layout, inside <body>.
// The project key is public: it can only send feedback to this project,
// from the origins allowed in Shyvo.`;

  if (mode === "npm") {
    return `${directive}${header}
import { ShyvoFeedback } from "@shyvo/feedback/react";

const project = ${framework.envAccess(key)};
const endpoint = ${framework.envAccess(endpoint)};

export function ShyvoFeedbackWidget() {
  if (!project || !endpoint) return null;
  return <ShyvoFeedback project={project} endpoint={endpoint} />;
}
`;
  }

  return `${directive}${header}
import { useEffect } from "react";

const project = ${framework.envAccess(key)};
const endpoint = ${framework.envAccess(endpoint)};
const SCRIPT_URL = ${JSON.stringify(setup.scriptUrl)};

export function ShyvoFeedbackWidget() {
  useEffect(() => {
    if (!project || !endpoint) return;
    if (document.querySelector("script[data-shyvo-feedback]")) return;
    const script = document.createElement("script");
    script.src = SCRIPT_URL;
    script.async = true;
    script.dataset.shyvoFeedback = "";
    script.dataset.project = project;
    script.dataset.endpoint = endpoint;
    document.body.appendChild(script);
  }, []);
  return null;
}
`;
}

const scriptTag = (setup) =>
  `<script async src="${setup.scriptUrl}" data-project="${setup.publicKey}" data-endpoint="${setup.endpoint}"></script>`;

const MOUNT_HINTS = {
  next: "app/layout.tsx (App Router) or pages/_app.tsx: render <ShyvoFeedbackWidget /> just before </body>.",
  "tanstack-start":
    "src/routes/__root.tsx: render <ShyvoFeedbackWidget /> inside the root document body, next to <Scripts />.",
  "react-router":
    "app/root.tsx: render <ShyvoFeedbackWidget /> inside <body>, next to <Scripts />.",
  "vite-react":
    "src/App.tsx (or main.tsx): render <ShyvoFeedbackWidget /> once at the top level.",
  astro: "src/layouts/<Base>.astro: paste the script tag before </body>.",
  sveltekit: "src/app.html: paste the script tag before </body>.",
  nuxt: "nuxt.config: app.head.script, or app.vue: paste the script tag.",
  vue: "index.html: paste the script tag before </body>.",
  html: "Every page (or the shared layout): paste the script tag before </body>.",
};

async function upsertEnv(path, values) {
  let current = "";
  try {
    current = await readFile(path, "utf8");
  } catch {
    current = "";
  }
  const added = [];
  for (const [name, value] of Object.entries(values)) {
    if (new RegExp(`^${name}=`, "m").test(current)) continue;
    added.push(`${name}=${value}`);
  }
  if (added.length === 0) return [];
  const prefix = current && !current.endsWith("\n") ? "\n" : "";
  await appendFile(
    path,
    `${prefix}# Shyvo feedback widget (public values)\n${added.join("\n")}\n`,
  );
  return added.map((line) => line.split("=")[0]);
}

/**
 * @param setup  the `setup_feedback_widget` tool result
 * @param options { root, mode: "auto"|"npm"|"script", writeEnv, dryRun }
 */
export async function installWidget(setup, options) {
  const root = options.root;
  const framework = await detectFramework(root);
  const mode =
    options.mode === "auto" || !options.mode
      ? framework.react && framework.hasFeedbackPackage
        ? "npm"
        : "script"
      : options.mode;

  const result = {
    framework: framework.label,
    frameworkId: framework.id,
    mode,
    files: [],
    env: [],
    nextSteps: [],
  };

  if (framework.react) {
    const ext = framework.typescript ? "tsx" : "jsx";
    const file = join(framework.srcDir, "components", `shyvo-feedback.${ext}`);
    if (!options.dryRun) {
      await mkdir(dirname(file), { recursive: true });
      await writeFile(file, reactComponent(framework, mode, setup));
    }
    result.files.push(relative(root, file));

    const envValues = {
      [`${framework.envPrefix}${ENV_KEYS.key}`]: setup.publicKey,
      [`${framework.envPrefix}${ENV_KEYS.endpoint}`]: setup.endpoint,
    };
    if (options.writeEnv !== false && !options.dryRun) {
      result.env = await upsertEnv(join(root, framework.envFile), envValues);
      result.envFile = framework.envFile;
    } else result.envValues = envValues;

    if (mode === "npm" && !framework.hasFeedbackPackage)
      result.nextSteps.push(`Install the package: npm install ${setup.npmPackage}`);
    result.nextSteps.push(`Mount it in ${MOUNT_HINTS[framework.id]}`);
    result.nextSteps.push(
      `Add the same two env values to the production environment (${Object.keys(envValues).join(", ")}).`,
    );
  } else {
    result.snippet = scriptTag(setup);
    result.nextSteps.push(`Paste the snippet in ${MOUNT_HINTS[framework.id]}`);
  }

  result.nextSteps.push(
    `Allowed origins: ${setup.allowedOrigins?.join(", ") ?? "(see Shyvo)"}. Feedback from any other origin is refused; add more with --origin.`,
  );
  result.nextSteps.push(
    "Open the app, click the Feedback button and send a test; it shows up in Shyvo > Feedback (`shyvo feedback list`).",
  );
  return result;
}
